const LETTER_TO_INDEX = { A: 0, B: 1, C: 2, D: 3 };
const VALID_DIFFICULTIES = new Set(["easy", "medium", "hard"]);

const normalizeQuestion = (raw, fallbackDifficulty) => {
  const question = String(raw?.question ?? "").trim();
  const options = (raw?.options ?? [])
    .map((option) => String(option ?? "").trim())
    .filter(Boolean);

  if (!question || options.length !== 4) {
    return null;
  }

  const letter = String(raw?.correctAnswer ?? "")
    .trim()
    .toUpperCase()
    .charAt(0);

  if (!(letter in LETTER_TO_INDEX)) {
    return null;
  }

  const explanation = String(raw?.explanation ?? "").trim();
  if (!explanation) {
    return null;
  }

  const rawDifficulty = String(raw?.difficulty ?? "")
    .trim()
    .toLowerCase();
  const difficulty = VALID_DIFFICULTIES.has(rawDifficulty)
    ? rawDifficulty
    : fallbackDifficulty;

  const sourceTopic = String(raw?.sourceTopic ?? "").trim().slice(0, 200);

  return {
    question,
    options,
    correctAnswer: letter,
    correctIndex: LETTER_TO_INDEX[letter],
    explanation,
    difficulty,
    ...(sourceTopic ? { sourceTopic } : {}),
  };
};

const validateAiQuizPayload = (
  payload,
  numberOfQuestions,
  difficultyMode,
) => {
  const title = String(payload?.title ?? "").trim();
  const description = String(payload?.description ?? "").trim();

  if (!title) {
    throw ApiError.internalServer(
      "AI returned an invalid quiz. Please try again later.",
    );
  }

  if (!Array.isArray(payload?.questions) || payload.questions.length === 0) {
    throw ApiError.internalServer(
      "AI returned an invalid quiz. Please try again later.",
    );
  }

  const distribution = getQuestionDifficultyDistribution(
    numberOfQuestions,
    difficultyMode,
  );

  const questions = payload.questions
    .map((item, index) =>
      normalizeQuestion(item, distribution[index] ?? "medium"),
    )
    .filter(Boolean);

  const deduped = dedupeQuestions(questions);

  if (deduped.length < Math.min(numberOfQuestions, 3)) {
    throw ApiError.internalServer(
      "AI returned an invalid quiz. Please try again later.",
    );
  }

  return {
    title: title.slice(0, 200),
    description: description.slice(0, 500) || "Quiz generated by AI",
    questions: deduped.slice(0, numberOfQuestions),
  };
};

const estimateMaxOutputTokens = (numberOfQuestions) =>
  Math.min(8000, 1200 + numberOfQuestions * 280);

const resolveSubjectIdFromContent = (content) =>
  content?.subjectId ?? content?.subject_id ?? null;

const buildSummaryContext = (summaryRecord) => {
  if (!summaryRecord) {
    return null;
  }

  return {
    summary: summaryRecord.summary,
    keyPoints: summaryRecord.keyPoints ?? summaryRecord.key_points ?? [],
    learningNotes:
      summaryRecord.learningNotes ?? summaryRecord.learning_notes ?? [],
  };
};

const resolveGenerationOptions = ({
  difficulty = "mixed",
  numberOfQuestions = 5,
  forceRegenerate = true,
} = {}) => ({
  difficulty,
  numberOfQuestions,
  forceRegenerate: forceRegenerate !== false,
});

const generateQuizWithAi = async ({
  buildPrompt,
  promptParams,
  numberOfQuestions,
  difficulty,
  avoidQuestions,
  variationSeed,
  strictRetry = false,
}) => {
  const prompt = buildPrompt({
    ...promptParams,
    numberOfQuestions,
    difficulty,
    variationSeed,
    avoidQuestions,
    strictRetry,
  });

  const { model } = getOpenAIConfig();
  const aiResult = await aiProviderService.generateJson({
    instructions: prompt.instructions,
    input: prompt.input,
    model,
    temperature: strictRetry ? 0.55 : 0.45,
    maxOutputTokens: estimateMaxOutputTokens(numberOfQuestions),
  });

  return validateAiQuizPayload(aiResult, numberOfQuestions, difficulty);
};

const persistGeneratedQuiz = async ({
  userId,
  subjectId,
  normalized,
  sourceDocumentId = null,
  difficulty,
  numberOfQuestions,
  model,
}) => {
  const existingTitles = await quizGeneratorRepository.findUserQuizTitles(userId);
  const uniqueTitle = resolveUniqueQuizTitle(
    normalized.title,
    new Set(existingTitles),
  );

  return quizGeneratorRepository.createAiQuiz({
    userId,
    subjectId,
    title: uniqueTitle,
    description: normalized.description,
    questions: normalized.questions,
    source: "ai_generated",
    sourceDocumentId,
    aiModel: model,
    generationDifficulty: difficulty,
    generationQuestionCount: numberOfQuestions,
  });
};

const generateAndSaveQuiz = async ({
  userId,
  subjectId,
  sourceDocumentId = null,
  buildPrompt,
  promptParams,
  difficulty,
  numberOfQuestions,
  forceRegenerate,
  cacheLookup,
  avoidLookup,
}) => {
  if (!forceRegenerate && cacheLookup) {
    const existing = await quizGeneratorRepository.findExistingAiQuiz(
      cacheLookup,
    );

    if (existing) {
      return serializeGeneratedQuiz(existing, difficulty);
    }
  }

  const avoidQuestions = mergeAvoidQuestionLists(
    await quizGeneratorRepository.findPreviousQuestionTexts(avoidLookup),
  );

  const variationSeed = createVariationSeed();
  const { model } = getOpenAIConfig();

  let normalized = await generateQuizWithAi({
    buildPrompt,
    promptParams,
    numberOfQuestions,
    difficulty,
    avoidQuestions,
    variationSeed,
  });

  if (normalized.questions.length < numberOfQuestions) {
    const retryAvoid = mergeAvoidQuestionLists(
      avoidQuestions,
      normalized.questions.map((item) => item.question),
    );

    normalized = await generateQuizWithAi({
      buildPrompt,
      promptParams,
      numberOfQuestions,
      difficulty,
      avoidQuestions: retryAvoid,
      variationSeed: createVariationSeed(),
      strictRetry: true,
    });
  }

  if (normalized.questions.length > numberOfQuestions) {
    normalized.questions = normalized.questions.slice(0, numberOfQuestions);
  }

  const saved = await persistGeneratedQuiz({
    userId,
    subjectId,
    normalized,
    sourceDocumentId,
    difficulty,
    numberOfQuestions,
    model,
  });

  return serializeGeneratedQuiz(saved, difficulty);
};

export const generateQuizFromDocument = async (
  userId,
  role,
  documentId,
  options = {},
) => {
  const { difficulty, numberOfQuestions, forceRegenerate } =
    resolveGenerationOptions(options);

  const content = await resolveAccessibleContent(userId, role, documentId);
  const subjectId = resolveSubjectIdFromContent(content);
  const documentText = await extractDocumentText(content);
  const summaryRecord = await summaryRepository.findByDocumentId(documentId);
  const summaryContext = buildSummaryContext(summaryRecord);

  const subjectName =
    subjectId != null
      ? (await getSubjectById(userId, subjectId).catch(() => null))?.name ?? ""
      : "";

  return generateAndSaveQuiz({
    userId,
    subjectId,
    sourceDocumentId: documentId,
    difficulty,
    numberOfQuestions,
    forceRegenerate,
    cacheLookup: {
      userId,
      sourceDocumentId: documentId,
      difficulty,
      questionCount: numberOfQuestions,
    },
    avoidLookup: {
      userId,
      sourceDocumentId: documentId,
    },
    buildPrompt: buildDocumentQuizPrompt,
    promptParams: {
      documentTitle: content.title,
      documentText,
      summaryContext,
      subjectName,
    },
  });
};

export const generateQuizFromSubject = async (
  userId,
  subjectId,
  options = {},
) => {
  const { difficulty, numberOfQuestions, forceRegenerate } =
    resolveGenerationOptions(options);
  const topic = String(options.topic ?? "").trim();

  const subject = await getSubjectById(userId, subjectId);

  return generateAndSaveQuiz({
    userId,
    subjectId,
    difficulty,
    numberOfQuestions,
    forceRegenerate,
    avoidLookup: {
      userId,
      subjectId,
    },
    buildPrompt: buildSubjectQuizPrompt,
    promptParams: {
      subjectName: subject.name,
      topic: topic || subject.name,
    },
  });
};

export const generatePracticeQuiz = async (userId, options = {}) => {
  const { difficulty, numberOfQuestions, forceRegenerate } =
    resolveGenerationOptions(options);
  const topic = String(options.topic ?? "").trim();

  if (!topic) {
    throw ApiError.badRequest("Topic is required to generate a practice quiz.");
  }

  const subjectId = options.subjectId ?? null;
  let subjectName = topic;

  if (subjectId) {
    const subject = await getSubjectById(userId, subjectId);
    subjectName = subject.name;
  }

  return generateAndSaveQuiz({
    userId,
    subjectId,
    difficulty,
    numberOfQuestions,
    forceRegenerate,
    avoidLookup: subjectId
      ? { userId, subjectId }
      : { userId, subjectId: null },
    buildPrompt: buildSubjectQuizPrompt,
    promptParams: {
      subjectName,
      topic,
    },
  });
};
