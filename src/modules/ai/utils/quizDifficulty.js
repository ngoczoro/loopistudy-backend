export const getQuestionDifficultyDistribution = (
  numberOfQuestions,
  mode = "mixed",
) => {
  const count = Number(numberOfQuestions);

  if (mode === "easy") {
    return Array(count).fill("easy");
  }

  const distribution =
    DISTRIBUTIONS[mode]?.[count] ?? DISTRIBUTIONS.mixed[count];

  if (distribution) {
    return [...distribution];
  }

  return getQuestionDifficultyDistribution(count, "mixed");
};
